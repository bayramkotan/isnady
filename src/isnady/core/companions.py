_TRIM_RE = re.compile(r"\s*-.*$|(?<!\w)(?:رضي الله|حدث\w*|اخبر\w*|انه|انها|يقول|تقول|قال|قالت|يحدث|كان|زوج النبي|صاحب|مولي)(?!\w).*$")


def is_companion_name(raw: str) -> bool:
    """The name as written in a chain is one of the Companions (only names that mean a Companion wherever they stand)."""
    name = _TRIM_RE.sub("", normalize(raw or ""))
    return " ".join(name.split()).strip(" ،,-") in FORMS
